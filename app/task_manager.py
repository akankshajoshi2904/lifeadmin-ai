
import os
from contextlib import contextmanager

import psycopg2


VALID_PRIORITIES = {"Low", "Medium", "High"}
VALID_STATUSES = {"Pending", "Completed"}


def get_database_url():
    """Read the PostgreSQL connection string from environment or Streamlit Secrets."""
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        try:
            import streamlit as st
            database_url = st.secrets.get("DATABASE_URL")
        except Exception:
            database_url = None

    if not database_url:
        raise RuntimeError(
            "DATABASE_URL is missing. Add it to Streamlit Cloud Secrets "
            "or your local .streamlit/secrets.toml file."
        )

    return database_url


def get_connection():
    """Open a PostgreSQL connection."""
    return psycopg2.connect(
        get_database_url(),
        sslmode="require",
        connect_timeout=10,
    )


@contextmanager
def database_connection():
    """Commit successful operations, roll back failures, and always close."""
    connection = get_connection()
    try:
        with connection:
            yield connection
    finally:
        connection.close()


def create_tasks_table():
    """Create the tasks table and its session index if needed."""
    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                CREATE TABLE IF NOT EXISTS tasks (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title TEXT NOT NULL,
                    due_date TEXT,
                    priority TEXT,
                    status TEXT DEFAULT 'Pending',
                    session_id TEXT
                )
                """
            )
            cursor.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_tasks_session_id
                ON tasks (session_id)
                """
            )


def _require_session_id(session_id):
    if not isinstance(session_id, str) or not session_id.strip():
        raise ValueError("A valid session ID is required.")
    return session_id


def task_exists(title, due_date, session_id):
    session_id = _require_session_id(session_id)

    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT id
                FROM tasks
                WHERE title = %s
                  AND due_date IS NOT DISTINCT FROM %s
                  AND status = 'Pending'
                  AND session_id = %s
                LIMIT 1
                """,
                (title, due_date, session_id),
            )
            return cursor.fetchone() is not None


def add_task(title, due_date=None, priority="Low", session_id=None):
    session_id = _require_session_id(session_id)

    if not isinstance(title, str) or not title.strip():
        raise ValueError("Task title cannot be empty.")

    if priority not in VALID_PRIORITIES:
        raise ValueError("Priority must be Low, Medium, or High.")

    title = title.strip()

    if task_exists(title, due_date, session_id):
        return False

    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO tasks (title, due_date, priority, session_id)
                VALUES (%s, %s, %s, %s)
                """,
                (title, due_date, priority, session_id),
            )

    return True


def get_tasks(session_id):
    session_id = _require_session_id(session_id)

    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT id, title, due_date, priority, status
                FROM tasks
                WHERE session_id = %s
                ORDER BY
                    CASE priority
                        WHEN 'High' THEN 1
                        WHEN 'Medium' THEN 2
                        WHEN 'Low' THEN 3
                        ELSE 4
                    END,
                    CASE WHEN due_date IS NULL THEN 1 ELSE 0 END,
                    due_date
                """,
                (session_id,),
            )
            return cursor.fetchall()


def update_task_status(task_id, status, session_id):
    session_id = _require_session_id(session_id)

    if status not in VALID_STATUSES:
        raise ValueError("Status must be Pending or Completed.")

    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                UPDATE tasks
                SET status = %s
                WHERE id = %s AND session_id = %s
                """,
                (status, task_id, session_id),
            )
            return cursor.rowcount == 1


def update_task_details(
    task_id,
    session_id,
    title=None,
    due_date=None,
    priority=None,
    status=None,
):
    """Update supplied task fields without changing other fields."""
    session_id = _require_session_id(session_id)

    fields = []
    values = []

    if title is not None:
        if not isinstance(title, str) or not title.strip():
            raise ValueError("Task title cannot be empty.")
        fields.append("title = %s")
        values.append(title.strip())

    if due_date is not None:
        if not isinstance(due_date, str) or not due_date.strip():
            raise ValueError("Use a valid date or None to clear the deadline.")
        fields.append("due_date = %s")
        values.append(due_date.strip())

    if priority is not None:
        if priority not in VALID_PRIORITIES:
            raise ValueError("Priority must be Low, Medium, or High.")
        fields.append("priority = %s")
        values.append(priority)

    if status is not None:
        if status not in VALID_STATUSES:
            raise ValueError("Status must be Pending or Completed.")
        fields.append("status = %s")
        values.append(status)

    if not fields:
        raise ValueError("No changes were provided.")

    values.extend([task_id, session_id])

    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                f"""
                UPDATE tasks
                SET {", ".join(fields)}
                WHERE id = %s AND session_id = %s
                """,
                tuple(values),
            )
            return cursor.rowcount == 1


def clear_task_due_date(task_id, session_id):
    """Remove a deadline without changing other task fields."""
    session_id = _require_session_id(session_id)

    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                UPDATE tasks
                SET due_date = NULL
                WHERE id = %s AND session_id = %s
                """,
                (task_id, session_id),
            )
            return cursor.rowcount == 1


def delete_task(task_id, session_id):
    """Delete a task only when it belongs to the current session."""
    session_id = _require_session_id(session_id)

    with database_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                DELETE FROM tasks
                WHERE id = %s AND session_id = %s
                """,
                (task_id, session_id),
            )
            return cursor.rowcount == 1
